const translationIndexes = Object.fromEntries(
  Object.entries(translations).map(([language, dictionary]) => [
    language,
    {
      phrases: Object.keys(dictionary)
        .filter((key) => key.includes(" "))
        .sort((left, right) => right.length - left.length)
        .map((phrase) => [
          new RegExp(phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi"),
          dictionary[phrase],
        ]),
      words: Object.fromEntries(
        Object.entries(dictionary)
          .filter(([key]) => !key.includes(" "))
          .map(([key, translation]) => [key.toLowerCase(), translation])
      ),
    },
  ])
);

function translateText(language, value) {
  const dictionary = translations[language];
  const index = translationIndexes[language];
  if (!dictionary || !value) return value;
  if (dictionary[value]) return dictionary[value];

  const preservedValues = [];
  let translated = value.replace(
    /\b[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}\b/g,
    (email) => {
      preservedValues.push(email);
      return `\uE000${preservedValues.length - 1}\uE001`;
    }
  );
  for (const [phraseMatcher, phraseTranslation] of index.phrases) {
    translated = translated.replace(phraseMatcher, phraseTranslation);
  }

  translated = translated.replace(/[A-Za-z]+(?:['’-][A-Za-z]+)*/g, (word) => {
    const lower = word.toLowerCase();
    const translatedWord = index.words[lower] || (lower.endsWith("s") ? index.words[lower.slice(0, -1)] : null);
    if (!translatedWord) return word;
    return word[0] === word[0].toUpperCase()
      ? translatedWord.charAt(0).toUpperCase() + translatedWord.slice(1)
      : translatedWord;
  });
  return translated.replace(/\uE000(\d+)\uE001/g, (_placeholder, index) => preservedValues[Number(index)]);
}

export function translateCurrent(value) {
  return translateText(activeLanguage, value);
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((stored) => {
        if (LANGUAGES.some((item) => item.code === stored)) {
          activeLanguage = stored;
          setLanguageState(stored);
        }
      })
      .catch((error) => console.error("Could not load saved language preference", error))
      .finally(() => setReady(true));
  }, []);

  const setLanguage = useCallback(async (nextLanguage) => {
    if (!LANGUAGES.some((item) => item.code === nextLanguage)) {
      throw new Error(`Unsupported language: ${nextLanguage}`);
    }
    await AsyncStorage.setItem(STORAGE_KEY, nextLanguage);
    activeLanguage = nextLanguage;
    setLanguageState(nextLanguage);
  }, []);

  const value = useMemo(
    () => ({
      language,
      languages: LANGUAGES,
      ready,
      setLanguage,
      translate: (value) => translateText(language, value),
    }),
    [language, ready, setLanguage]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within a LanguageProvider");
  return context;
}
